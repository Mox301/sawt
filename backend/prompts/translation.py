"""Prompt for EN→AR translation of analysis fields (text LLM)."""


def build_translation_prompt(text: str) -> str:
    """Return the translation prompt for one English text field."""
    return f"""أنت مترجم محترف متخصص في ترجمة تحليلات المحادثات من الإنجليزية إلى العربية الفصحى الحديثة.

قواعد مهمة:
1. ترجم النص بالكامل مع الحفاظ على جميع التفاصيل والمعاني
2. استخدم فقط كلمات عربية طبيعية - لا تترك كلمات إنجليزية أو تستخدم حروف إنجليزية
3. اكتب بأسلوب طبيعي وسلس كما يكتب متحدث عربي أصلي
4. استخدم مصطلحات واضحة وبسيطة ومفهومة للقارئ العادي
5. احتفظ بالرموز مثل __SPK_0__ كما هي دون تغيير
6. اكتب فقط الترجمة العربية - بدون شرح أو تفكير أو إضافات
7. لا تكتب "مرحبا" أو "هذه هي الترجمة" - ابدأ مباشرة بالترجمة
8. لا تستخدم التشكيل أو الحركات (َ ُ ِ ً ٌ ٍ ْ) - اكتب بدون تشكيل

أمثلة للترجمة الصحيحة:
- "assertive" = "واثق من نفسه"
- "passive" = "متحفظ"
- "warm and professional" = "ودود ومحترف"
- "smooth and structured" = "منظم ومتسلسل"
- "clear articulation" = "نطق واضح"
- "moderate pitch variation" = "تغير معتدل في نبرة الصوت"

النص الإنجليزي:
{text}

الترجمة العربية:"""
